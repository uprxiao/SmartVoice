export function reviewReason(locale: Locale, reason: string | null | undefined): string | null {
  if (!reason) return null;
  const table = locale === 'en' ? REVIEW_REASONS_EN : REVIEW_REASONS_ZH;
  return table[reason] ?? null;
}

export function tr(locale: Locale, key: string, vars?: Record<string, string | number>): string {
  const entry = DICT[key];
  let text = entry ? entry[locale] ?? entry['zh-CN'] : key;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replaceAll(`{${name}}`, String(value));
    }
  }
  return text;
}
